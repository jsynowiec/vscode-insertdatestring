export function normalizeLocale(configuredLocale: string | undefined): string {
  return configuredLocale?.trim().toLowerCase() ?? "";
}

export function isSupportedLocale(locale: string): boolean {
  return supportedLocaleKeys.has(locale);
}

export async function resolveConfiguredLocale(
  configuredLocale: string | undefined,
): Promise<LocaleResolution> {
  const locale = normalizeLocale(configuredLocale);
  if (!locale) return {};
  if (locale === "en") return { locale };
  if (!isSupportedLocale(locale)) return { invalidLocale: locale };

  const loadLocale = localeLoaders[locale];
  if (!loadLocale) return { invalidLocale: locale };

  try {
    await loadLocale();
    return { locale };
  } catch {
    return { invalidLocale: locale };
  } finally {
    dayjs.locale("en");
  }
}
